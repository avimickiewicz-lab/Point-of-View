export const UI_LANGS = ['ru', 'en'];
let lang = 'ru';

export const getLang = () => lang;

/** Язык по умолчанию — из настроек браузера. */
export function detectLang() {
  const l = (navigator.languages?.[0] || navigator.language || 'ru').toLowerCase();
  return l.startsWith('ru') ? 'ru' : 'en';
}

export function t(key, params) {
  let s = DICT[lang][key] ?? DICT.ru[key] ?? key;
  if (Array.isArray(s)) s = s[0];
  if (params) s = s.replace(/\{(\w+)\}/g, (m, k) => (params[k] ?? m));
  return s;
}

/** Форма слова для числа n: plural(5, 'rec.symbols') → «символов» / «cells». */
export function plural(n, key) {
  const forms = DICT[lang][key] ?? DICT.ru[key];
  if (lang === 'en') return n === 1 ? forms[0] : forms[1];
  const m10 = n % 10, m100 = n % 100;
  if (m10 === 1 && m100 !== 11) return forms[0];
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return forms[1];
  return forms[2];
}

/** Число с десятичным разделителем языка интерфейса. */
export const fmt = (x, digits = 1) =>
  x.toLocaleString(lang === 'ru' ? 'ru-RU' : 'en-US', { minimumFractionDigits: digits, maximumFractionDigits: digits });

/** Переводит разметку и запоминает язык. */
export function setLang(l, root = document) {
  lang = UI_LANGS.includes(l) ? l : 'ru';
  document.documentElement.lang = lang;
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => el.setAttribute('aria-label', t(el.dataset.i18nAria)));
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => el.setAttribute('placeholder', t(el.dataset.i18nPlaceholder)));
  const meta = document.querySelector('meta[name="description"]');
  if (meta) meta.content = lang === 'ru'
    ? 'Point of view — распознавание шрифта Брайля по фотографии'
    : 'Point of view — Braille recognition from a photo';
}
